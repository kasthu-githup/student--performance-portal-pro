const generateStudentMarks = (basePercentage: number): Record<string, SubjectMarks> => {
  const map: Record<string, SubjectMarks> = {};
  SUBJECT_CATALOG.forEach((subj, idx) => {
    const variance = (idx % 3 === 0 ? 3 : idx % 2 === 0 ? -2 : 1);
    const pct = Math.min(98, Math.max(55, basePercentage + variance));
    const internal1 = Math.round((pct / 100) * 50);
    const internal2 = Math.round(((pct + (idx % 2 === 0 ? 2 : -2)) / 100) * 50);
    const modelExam = Math.round((pct / 100) * 100);
    const assignment = Math.min(10, Math.round((pct / 100) * 10));

    let grade = 'B+';
    if (pct >= 90) grade = 'O';
    else if (pct >= 80) grade = 'A+';
    else if (pct >= 70) grade = 'A';
    else if (pct >= 60) grade = 'B+';
    else if (pct >= 50) grade = 'B';
    else grade = 'U';

    map[subj.code] = {
      subjectCode: subj.code,
      subjectName: subj.name,
      internal1,
      internal2,
      modelExam,
      assignment,
      totalPercentage: pct,
      grade,
    };
  });
  return map;
};

const generateSubjectAttendance = (percentage: number): Record<string, SubjectAttendance> => {
  const map: Record<string, SubjectAttendance> = {};
  SUBJECT_CATALOG.forEach((subj) => {
    const conducted = 48;
    const attended = Math.round((percentage / 100) * conducted);
    const od = 2;
    map[subj.code] = {
      subjectCode: subj.code,
      subjectName: subj.name,
      facultyName: subj.facultyName || 'Dr. R. Sharma',
      conducted,
      attended,
      od,
      percentage: Math.round(((attended + od) / conducted) * 100),
    };
  });
  return map;
};

